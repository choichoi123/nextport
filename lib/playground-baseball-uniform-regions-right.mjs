// Split at each pose's measured knee cross-section, rather than a screen-Y row.
// Both halves share the same U section, repeat count and phase at the join.
function clipAtKnee(polygon, left, right, sign) {
  const side = point => ((right[0] - left[0]) * (point[1] - left[1]) - (right[1] - left[1]) * (point[0] - left[0])) * sign;
  const result = [];
  for (let i = 0, previous = polygon[polygon.length - 1]; i < polygon.length; previous = polygon[i++]) {
    const current = polygon[i], a = side(previous), b = side(current);
    if ((a >= 0) !== (b >= 0)) {
      const t = a / (a - b);
      result.push([previous[0] + t * (current[0] - previous[0]), previous[1] + t * (current[1] - previous[1])]);
    }
    if (b >= 0) result.push(current);
  }
  return result;
}

function pilotLeg(polygon, topLeft, topRight, kneeLeft, kneeRight, bottomLeft, bottomRight, phase = 0) {
  return [
    pilotPanel('pants', clipAtKnee(polygon, kneeLeft, kneeRight, -1), topLeft, topRight, kneeLeft, kneeRight, { phase, fadeEdges: ['left', 'right', 'top'] }),
    pilotPanel('pants', clipAtKnee(polygon, kneeLeft, kneeRight, 1), kneeLeft, kneeRight, bottomLeft, bottomRight, { phase, fadeEdges: ['left', 'right', 'bottom'] }),
  ];
}

