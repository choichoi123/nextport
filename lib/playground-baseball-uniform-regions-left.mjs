const sleeveLeftUnit = ([x, y]) => { const length = Math.hypot(x, y) || 1; return [x / length, y / length]; };
const sleeveLeftDot = (a, b) => a[0] * b[0] + a[1] * b[1];
const sleeveLeftOffset = (point, direction, amount) => [point[0] + direction[0] * amount, point[1] + direction[1] * amount];
const sleeveLeftClip = (polygon, elbow, tangent, sign) => {
  const output = [];
  const signed = point => sleeveLeftDot([point[0] - elbow[0], point[1] - elbow[1]], tangent) * sign;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[j], b = polygon[i], da = signed(a), db = signed(b);
    if ((da >= 0) !== (db >= 0)) {
      const t = da / (da - db);
      output.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
    }
    if (db >= 0) output.push(b);
  }
  return output;
};
const sleeveLeftContains = (quad, point) => {
  const crosses = quad.map((a, index) => {
    const b = quad[(index + 1) % quad.length];
    return (b[0] - a[0]) * (point[1] - a[1]) - (b[1] - a[1]) * (point[0] - a[0]);
  });
  return crosses.every(value => value >= -0.01) || crosses.every(value => value <= 0.01);
};
// A fixed two-piece cloth ribbon annotates the unchanged arm pixels. The shared
// elbow edge and global V keep the fabric tile continuous through the bend.
const sleeveLeftArm = (polygon, [proximal, elbow, distal]) => {
  const upperDirection = sleeveLeftUnit([elbow[0] - proximal[0], elbow[1] - proximal[1]]);
  const lowerDirection = sleeveLeftUnit([distal[0] - elbow[0], distal[1] - elbow[1]]);
  const tangent = sleeveLeftUnit([upperDirection[0] + lowerDirection[0], upperDirection[1] + lowerDirection[1]]);
  const normal = [-tangent[1], tangent[0]];
  const upper = sleeveLeftClip(polygon, elbow, tangent, -1);
  const lower = sleeveLeftClip(polygon, elbow, tangent, 1);
  const elbowPoints = [...upper, ...lower].filter(point => Math.abs(sleeveLeftDot([point[0] - elbow[0], point[1] - elbow[1]], tangent)) < 0.01);
  const projections = elbowPoints.map(point => sleeveLeftDot([point[0] - elbow[0], point[1] - elbow[1]], normal));
  const low = Math.min(...projections) - 4, high = Math.max(...projections) + 4;
  const jointCenter = sleeveLeftOffset(elbow, normal, (low + high) / 2);
  let radius = (high - low) / 2;
  const upperNormal = [-upperDirection[1], upperDirection[0]], lowerNormal = [-lowerDirection[1], lowerDirection[0]];
  const before = Math.min(0, ...upper.map(point => sleeveLeftDot([point[0] - proximal[0], point[1] - proximal[1]], upperDirection))) - 5;
  const after = Math.max(0, ...lower.map(point => sleeveLeftDot([point[0] - distal[0], point[1] - distal[1]], lowerDirection))) + 5;
  let start = sleeveLeftOffset(proximal, upperDirection, before), end = sleeveLeftOffset(distal, lowerDirection, after);
  let upperWidth = Math.max(12, ...upper.map(point => Math.abs(sleeveLeftDot([point[0] - start[0], point[1] - start[1]], upperNormal)))) + 5;
  let lowerWidth = Math.max(12, ...lower.map(point => Math.abs(sleeveLeftDot([point[0] - end[0], point[1] - end[1]], lowerNormal)))) + 5;
  let edges;
  for (let attempt = 0; attempt < 12; attempt++) {
    const sharedLeft = sleeveLeftOffset(jointCenter, normal, -radius), sharedRight = sleeveLeftOffset(jointCenter, normal, radius);
    const startLeft = sleeveLeftOffset(start, upperNormal, -upperWidth), startRight = sleeveLeftOffset(start, upperNormal, upperWidth);
    const endLeft = sleeveLeftOffset(end, lowerNormal, -lowerWidth), endRight = sleeveLeftOffset(end, lowerNormal, lowerWidth);
    edges = { sharedLeft, sharedRight, startLeft, startRight, endLeft, endRight };
    const upperQuad = [startLeft, startRight, sharedRight, sharedLeft], lowerQuad = [sharedLeft, sharedRight, endRight, endLeft];
    if (upper.every(point => sleeveLeftContains(upperQuad, point)) && lower.every(point => sleeveLeftContains(lowerQuad, point))) break;
    radius *= 1.08; upperWidth *= 1.08; lowerWidth *= 1.08;
    start = sleeveLeftOffset(start, upperDirection, -2); end = sleeveLeftOffset(end, lowerDirection, 2);
  }
  const { sharedLeft, sharedRight, startLeft, startRight, endLeft, endRight } = edges;
  return [
    { polygon: upper, topLeft: startLeft, topRight: startRight, bottomLeft: sharedLeft, bottomRight: sharedRight, vStart: 0, vEnd: 0.5, repeatU: 1, repeatV: 2 },
    { polygon: lower, topLeft: sharedLeft, topRight: sharedRight, bottomLeft: endLeft, bottomRight: endRight, vStart: 0.5, vEnd: 1, repeatU: 1, repeatV: 2 },
  ];
};

