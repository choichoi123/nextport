const leftOfEdge = (polygon, from, to) => {
  const distance = point => (to[0] - from[0]) * (point[1] - from[1]) - (to[1] - from[1]) * (point[0] - from[0]);
  const clipped = [];
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[j], b = polygon[i], da = distance(a), db = distance(b);
    if ((da >= 0) !== (db >= 0)) {
      const t = da / (da - db);
      clipped.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
    }
    if (db >= 0) clipped.push(b);
  }
  return clipped;
};
